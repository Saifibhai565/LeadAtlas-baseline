import { analytics } from "@/lib/analytics";
import { currentUser } from "@/lib/auth";
import { APP_NAME } from "@/lib/utils";

export const dynamic = "force-dynamic";

/** A clean printable report page (the browser's "Save as PDF" turns it into a PDF). */
export async function GET() {
  const user = await currentUser();
  if (!user) return new Response("Please sign in.", { status: 401 });
  const d = await analytics(user.wsId);
  const n = (x: number) => x.toLocaleString("en-US");
  const row = (a: string, b: string) => `<tr><td>${a}</td><td style="text-align:right">${b}</td></tr>`;
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>Report</title>
<style>
  body{font-family:Arial,Helvetica,sans-serif;color:#1a2230;max-width:720px;margin:32px auto;padding:0 20px}
  h1{font-size:24px;margin:0} .muted{color:#5b6575;font-size:13px}
  h2{font-size:15px;margin:28px 0 8px;border-bottom:2px solid #F2B43C;padding-bottom:4px}
  table{width:100%;border-collapse:collapse;font-size:14px} td{padding:6px 0;border-bottom:1px solid #eee}
  .tiles{display:flex;gap:12px;margin-top:14px} .tile{flex:1;border:1px solid #e3e7ed;border-radius:10px;padding:12px}
  .tile b{display:block;font-size:22px} .print{margin:20px 0}
  @media print{.print{display:none}}
</style></head><body>
  <div class="print"><button onclick="window.print()" style="padding:10px 16px;border:0;border-radius:8px;background:#141A23;color:#fff;cursor:pointer">Print or save as PDF</button></div>
  <h1>${APP_NAME} report</h1>
  <p class="muted">${user.name} · ${new Date().toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" })}</p>
  <div class="tiles">
    <div class="tile"><span class="muted">Win rate</span><b>${d.roi.winRate}%</b></div>
    <div class="tile"><span class="muted">Deals won</span><b>${n(d.roi.wonCount)}</b></div>
    <div class="tile"><span class="muted">Value won</span><b>${n(d.roi.wonValue)}</b></div>
  </div>
  <h2>Funnel</h2><table>${d.funnel.map((f) => row(f.stage, n(f.count))).join("")}</table>
  <h2>Replies</h2><table>${row("Positive", n(d.sentiment.positive))}${row("Neutral", n(d.sentiment.neutral))}${row("Negative", n(d.sentiment.negative))}</table>
  ${d.leaderboard.length ? `<h2>Mailboxes</h2><table>${d.leaderboard.map((m) => row(m.name, `${n(m.sent)} sent · ${m.openRate}% opened`)).join("")}</table>` : ""}
  <p class="muted" style="margin-top:30px">Generated by ${APP_NAME}.</p>
</body></html>`;
  return new Response(html, { headers: { "Content-Type": "text/html; charset=utf-8" } });
}
